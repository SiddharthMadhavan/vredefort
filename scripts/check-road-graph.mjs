import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { buildRoadGraph, distanceMetres } from './road-graph.mjs'

const feature = (coordinates, id) => ({ type: 'Feature', id, properties: { highway: 'primary' }, geometry: { type: 'LineString', coordinates } })
const fixture = (...features) => buildRoadGraph({ type: 'FeatureCollection', features })
const a = [77.59, 12.97], b = [77.60, 12.97], c = [77.61, 12.97], d = [77.60, 12.98]
const t = fixture(feature([a, b, c], 1), feature([b, d], 2))
assert.equal(t.nodes.length, 4)
assert.equal(t.edges.length, 3)
assert.equal(t.nodes.filter(node => node.kind === 'junction_candidate').length, 1)
assert.equal(t.nodes.find(node => node.lon === b[0] && node.lat === b[1]).degree, 3)
const crossing = fixture(feature([a, c], 1), feature([[77.60, 12.96], d], 2))
assert.equal(crossing.nodes.length, 4, 'Crossing lines without shared stored vertices must not become junctions')
assert.equal(crossing.edges.length, 2)
const curved = fixture(feature([a, [77.595, 12.975], b], 1))
assert.equal(curved.nodes.length, 2)
assert.equal(curved.edges[0].coordinates.length, 3)
assert.ok(curved.edges[0].length_m > distanceMetres(a, b))
const loop = fixture(feature([a, b, d, a], 1))
assert.equal(loop.nodes.length, 1)
assert.equal(loop.edges[0].source, loop.edges[0].target)
assert.equal(loop.nodes[0].degree, 2)
const parallel = fixture(feature([a, b], 1), feature([a, b], 2))
assert.equal(parallel.edges.length, 2)
assert.equal(parallel.nodes[0].degree, 2)
const zeroLength = fixture(feature([a, a], 1), feature([a, b], 2))
assert.equal(zeroLength.edges.length, 1)
assert.equal(zeroLength.excluded_source_features.length, 1)
const graph = JSON.parse(await readFile(new URL('../data/bengaluru-road-graph.json', import.meta.url), 'utf8'))
const nodes = new Map(graph.nodes.map(node => [node.id, node]))
assert.equal(nodes.size, graph.nodes.length)
assert.equal(new Set(graph.edges.map(edge => edge.id)).size, graph.edges.length)
for (const edge of graph.edges) {
  const from = nodes.get(edge.source), to = nodes.get(edge.target)
  assert.ok(from && to)
  assert.deepEqual(edge.coordinates[0], [from.lon, from.lat])
  assert.deepEqual(edge.coordinates.at(-1), [to.lon, to.lat])
  assert.ok(edge.length_m > 0)
  assert.ok(from.edge_ids.includes(edge.id) && to.edge_ids.includes(edge.id))
}
assert.equal(graph.nodes.reduce((sum, node) => sum + node.degree, 0), graph.edges.length * 2)
graph.nodes.forEach((node, index) => assert.equal(node.number, index + 1))
const source = JSON.parse(await readFile(new URL('../public/data/bengaluru-roads.geojson', import.meta.url), 'utf8'))
assert.deepEqual(buildRoadGraph(source), graph, 'Graph must rebuild deterministically')
const sourceLength = source.features.reduce((sum, feature) => sum + feature.geometry.coordinates.slice(1).reduce((length, point, i) => length + distanceMetres(feature.geometry.coordinates[i], point), 0), 0)
const edgeLength = graph.edges.reduce((sum, edge) => sum + edge.length_m, 0)
assert.ok(Math.abs(sourceLength - edgeLength) < graph.edges.length * .00051, 'Splitting must preserve all source road length')
console.log(`Graph checks passed: ${graph.nodes.length} nodes, ${graph.edges.length} edges; fixtures, endpoints, degrees, deterministic IDs and length conservation.`)
